#!/usr/bin/env python3
"""Build the minstrel firmware's song table from a ROM manifest.

Reads a CSV with song_title and file columns (tools/roms/roms.csv
by default). Each file is a generated *_rom.h header: comment lines, one of
which says "One 12-bit frame every N ms", then one 0x... word per frame.
Songs keep the CSV's row order, which becomes the song id.

Writes firmware/songs.h with the frames as flash-resident const
arrays, a SONGS table and LIBRARY_CRC (CRC-32 over every name, step and frame),
which players compare to tell whether they carry the same library.
"""

import argparse
import csv
import re
import struct
import sys
import zlib
from pathlib import Path

from .paths import REPO, ROMS, SONG_TABLE

STEP_RE = re.compile(r"every\s+(\d+)\s+ms")
WORD_RE = re.compile(r"0x([0-9a-fA-F]+)")


def read_rom(path):
    step_ms = None
    frames = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if line.startswith("//"):
            match = STEP_RE.search(line)
            if match and step_ms is None:
                step_ms = int(match.group(1))
            continue
        for word in WORD_RE.findall(line):
            value = int(word, 16)
            if value > 0x0FFF:
                raise ValueError(f"{path.name}: word 0x{value:X} exceeds 12 bits")
            frames.append(value)
    if step_ms is None:
        raise ValueError(f"{path.name}: no 'One 12-bit frame every N ms' line")
    if not frames:
        raise ValueError(f"{path.name}: no frames")
    return step_ms, frames


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def source_label(path):
    try:
        return path.resolve().relative_to(REPO)
    except ValueError:
        return path


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--csv", type=Path, default=ROMS / "roms.csv")
    parser.add_argument("--output", type=Path, default=SONG_TABLE)
    args = parser.parse_args()

    songs = []
    with args.csv.open(newline="") as f:
        for row in csv.DictReader(f):
            path = args.csv.parent / row["file"]
            step_ms, frames = read_rom(path)
            expected = row.get("frames")
            if expected and int(expected) != len(frames):
                sys.exit(f"{path.name}: CSV says {expected} frames, header has {len(frames)}")
            songs.append((row["song_title"].strip(), step_ms, frames, path.name))

    if not songs:
        sys.exit(f"{args.csv}: no songs")
    if len(songs) > 255:
        sys.exit("song ids are 8-bit; at most 255 songs")

    crc = 0
    for name, step_ms, frames, _ in songs:
        crc = zlib.crc32(name.encode(), crc)
        crc = zlib.crc32(struct.pack("<HH", step_ms, len(frames)), crc)
        crc = zlib.crc32(struct.pack(f"<{len(frames)}H", *frames), crc)

    out = [
        "// Generated by tools/src/minstrel_tools/build_songs.py (minstrel-build-songs) - do not edit.",
        f"// Source: {source_label(args.csv)}",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct Song {",
        "  const char *name;",
        "  uint16_t stepMs;",
        "  uint16_t count;",
        "  const uint16_t *frames;",
        "};",
        "",
    ]
    for i, (name, step_ms, frames, source) in enumerate(songs):
        out.append(f"// {source}")
        out.append(f"static const uint16_t SONG_{i}_FRAMES[{len(frames)}] = {{")
        for start in range(0, len(frames), 12):
            chunk = frames[start:start + 12]
            out.append("  " + ", ".join(f"0x{w:03X}" for w in chunk) + ",")
        out.append("};")
        out.append("")
    out.append("static const Song SONGS[] = {")
    for i, (name, step_ms, frames, _) in enumerate(songs):
        out.append(f"  {{{c_string(name)}, {step_ms}, {len(frames)}, SONG_{i}_FRAMES}},")
    out.append("};")
    out.append("static const int SONG_COUNT = sizeof(SONGS) / sizeof(SONGS[0]);")
    out.append(f"static const uint32_t LIBRARY_CRC = 0x{crc:08X};")
    out.append("")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(out))
    total = sum(len(s[2]) for s in songs)
    print(f"{args.output}: {len(songs)} songs, {total} frames, library CRC 0x{crc:08X}")


if __name__ == "__main__":
    main()
